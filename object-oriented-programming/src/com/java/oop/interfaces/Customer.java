package com.java.oop.interfaces;

public class Customer {
    int id;
    String name;
    String email;
    long phoneNo;
    long aadharNo;

    public Customer(int id, String name, String email, long phoneNo, long aadharNo) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.phoneNo = phoneNo;
        this.aadharNo = aadharNo;
    }
}
